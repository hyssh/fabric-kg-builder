SOURCE_SHA256 = "b29900d0eccf3e0736c785911b86a18a9a616fdaa7edc8b7dcaeb432d0e7e5cf"
WORKSPACE = "00000000-0000-0000-0000-000000000001"


@pytest.fixture(scope="module")
def public_pdf():
    path = Path(os.environ.get(
        "FKG_SURFACE_PDF", "sample_data/Surface_Troubleshootings/Surface_Go_4_Service_Guide.pdf",
    ))
    if not path.is_file():
        pytest.skip("Approved public Surface snapshot not supplied; no fallback/download")
    raw = path.read_bytes()
    assert len(raw) == 5_445_106 and hashlib.sha256(raw).hexdigest() == SOURCE_SHA256
    return path, raw


class _ManualPage16Proposals:
    """Fixed scope, original-text anchors; not autonomous extraction or truth."""

    def __init__(self):
        self.emitted = False

    def complete(self, *, prompt, work_unit):
        heading, step = "Hardware Troubleshooting Approach", "Update device"
        text = work_unit.text
        if self.emitted or heading not in text or step not in text:
            return {"candidates": []}
        self.emitted = True

        def anchor(quote):
            start = work_unit.slice_start + text.index(quote)
            return {
                "span_start": start, "span_end": start + len(quote),
                "quote": quote, "model_authored_evidence_id": None,
            }

        def entity(local_id, observed_type, label):
            return {
                "candidate_kind": "entity", "local_id": local_id,
                "observed_type": observed_type, "label": label, "aliases": [],
                "identity_key": {}, "stable_source_identity": None, "anchors": [anchor(label)],
            }

        region = text[text.index(heading):text.index(step) + len(step)]
        return {"candidates": [
            entity("manual-page16-heading", "Record", heading),
            entity("manual-page16-step1", "Subject", step),
            {
                "candidate_kind": "relationship", "source_local_id": "manual-page16-heading",
                "target_local_id": "manual-page16-step1", "observed_predicate": "describes",
                "direction": "source_to_target", "governed_context": "manual bounded page16 annotation",
                "member_role_id": None, "member_order": None, "anchor": anchor(region),
            },
            {
                "candidate_kind": "property", "owner_local_id": "manual-page16-step1",
                "observed_property": "Reading", "value": step, "normalized_value": step,
                "temporal_key": None, "anchor": anchor(step),
            },
        ]}


def test_surface_local_adapter_to_publication_archive_field(public_pdf, tmp_path):
    source_path, _ = public_pdf
    producer = tmp_path / "producer"
    source = producer / "source"
    source.mkdir(parents=True)
    shutil.copyfile(source_path, source / "Surface_Go_4_Service_Guide.pdf")
    intake = _intake("surface")
    intake["competency_questions"] = [
        {"id": f"cq:q{index}", "question": text, "business_critical": False}
        for index, text in enumerate(intake["competency_questions"], start=1)
    ]
    manual_identity = canonical_sha256({"scope": "manual_bounded_source_annotation/page16/v1"})
    preflight = preflight_l1_inputs(
        source_path=source, intake_raw=intake, project_id="project:surface-p0-local",
        run_id="run:surface-p0-local", model_version="manual_bounded_source_annotation/1.0.0",
        model_hash=manual_identity,
    )
    candidates = _candidates("surface")
    candidates["completeness_candidates"] = []
    candidates["semantic_type_candidates"][1]["proposed_type"]["declared_properties"] = [{
        "property_id": "property:surface.reading", "display_name": "Reading",
        "value_type": "string", "required": False,
    }]
    prepared = prepare_l1_stage(preflight, candidates=candidates)
    l1 = producer / ".fkg/l1"
    domain = producer / "manual-test-domain.yaml"
    finalized = finalize_l1_stage(
        prepared, decision="approve", actor="offline-fixture@example.test",
        state_root=l1, domain_path=domain,
    )
    assert finalized.status == "succeeded"
    inputs = load_l2_inputs(l1_state_root=l1, domain_path=domain)
    service = _ManualPage16Proposals()
    l2 = run_l2(
        reader=indexed_corpus_reader(inputs.corpus_manifest, source, project_id="project:surface-p0-local"),
        service=service, state_root=producer / ".fkg/l2", l1_state_root=l1,
        domain_path=domain, prompt_hash=manual_identity,
        model_version="manual_bounded_source_annotation/1.0.0", model_hash=manual_identity,
    )
    assert l2.receipt.status == "succeeded" and service.emitted
    l3 = run_l3(
        state_root=producer / ".fkg/l3", l2_state_root=producer / ".fkg/l2",
        l1_state_root=l1, domain_path=domain,
    )
    l4 = run_l4(l3, state_root=producer / ".fkg/l4")
    compilation = _compile(l4.run_root, l3.state_root, WORKSPACE, "surfacep0")
    _materialize(compilation, producer / "publication")
    semantic_type = next(
        item for item in compilation.definitions["parquet"]["semantic_types"] if item["properties"]
    )
    table, field = semantic_type["physical_table_id"], semantic_type["properties"][0]["physical_column_id"]
    record = compilation.tables[table].to_pylist()[0]["__canonical_id"]
    archive = tmp_path / "consumer-archive"
    created = create_archive(
        l1_state=l1, domain=domain, l2_state=producer / ".fkg/l2", l3_root=l3.state_root,
        l4_run=l4.run_root, publication=producer / "publication", workspace_id=WORKSPACE,
        name_prefix="surfacep0", publication_version="local-manual-surface-001",
        out=archive, source_root=source,
    )
    producer.rename(tmp_path / "producer-unavailable")
    result = resolve_archive(
        archive=archive, archive_hash=created["archive_hash"],
        publication_version="local-manual-surface-001", table=table, record=record, field=field,
    )
    assert result["resolution_status"] == "COMPLETE"
    assert result["field_value"] == "Update device"
    assert result["original_source_retrieval_verified"] is True
    assert len(result["observations"]) == 1
    observation = result["observations"][0]
    assert observation["source"]["original_byte_hash"] == SOURCE_SHA256
    assert observation["source_unit"]["locator"]["page"] == 16
    assert observation["raw_location"]["status"] == "UNAVAILABLE"  # No actual DI cache supplied.
    location = observation["local_source_location"]
    assert location["status"] == "UNIQUE_TEXT_MATCH"
    assert location["text_matches"][0]["line_bboxes"][0] == pytest.approx(
        [87.02, 464.04, 148.63, 476.88], abs=0.02,
    )
    assert result["live_fabric_verified"] is False


def test_surface_original_table_and_figure_geometry_only(public_pdf):
    _, raw = public_pdf
    table_location = pdf_source_location(raw, page_number=2, quote=None)
    cells = [
        cell for table in table_location["context_tables"] for cell in table["cells"]
        if cell["row_index"] == 2 and cell["column_index"] == 0 and cell["extracted_value"] == "B"
    ]
    assert any(cell["bbox"] == pytest.approx([47.64, 96.98, 132.62, 124.10], abs=0.02) for cell in cells)
    figure_location = pdf_source_location(raw, page_number=18, quote=None)
    assert any(
        image["bbox"] == pytest.approx([89.15, 143.80, 278.17, 280.65], abs=0.02)
        for image in figure_location["context_figures"]
    )
    assert figure_location["status"] == "PAGE_CONTEXT_ONLY"
    assert figure_location["is_document_intelligence"] is False
    assert figure_location["assertion_trust_promoted"] is False
